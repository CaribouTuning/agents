export function natureModifier(natureIndex, stat) {
  const n = NATURES[natureIndex % NATURES.length];
  if (!n || !n[1]) return 1;
  if (n[1] === stat) return 1.1;
  if (n[2] === stat) return 0.9;
  return 1;
}

export function natureName(i) { return NATURES[i % NATURES.length][0]; }
